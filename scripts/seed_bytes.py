"""Writes Seed/Bytes.lean: the hex0 seeds and their annotated sources, as bytes.

Usage: seed_bytes.py BOOTSTRAP_SEEDS_DIR STAGE0_PE32_DIR > Seed/Bytes.lean

The theorems in Seed.lean are about these arrays, so CI regenerates the file
from pinned checkouts and requires it to come out unchanged.
"""
import pathlib
import sys

PER_LINE = 20

# Lean name, which checkout, path inside it, and what it is.
FILES = [
    ("linuxSource", 0, "POSIX/x86/hex0_x86.hex0", "The Linux x86 seed's annotated source"),
    ("linuxSeed", 0, "POSIX/x86/hex0-seed", "The Linux x86 seed"),
    ("pe32Source", 1, "x86/hex0_x86.hex0", "The Windows PE32 seed's annotated source"),
    ("pe32Seed", 1, "bootstrap-seeds/PE32/i386/hex0-seed.exe", "The Windows PE32 seed"),
]
CHECKOUTS = ["bootstrap-seeds", "stage0-pe32"]


def array(data):
    rows = []
    for i in range(0, len(data), PER_LINE):
        rows.append("  " + ", ".join(str(b) for b in data[i : i + PER_LINE]))
    return "#[\n" + ",\n".join(rows) + "\n]"


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: seed_bytes.py BOOTSTRAP_SEEDS_DIR STAGE0_PE32_DIR")
    roots = sys.argv[1:3]
    out = [
        "/-! The hex0 seeds and their annotated sources, as bytes. Generated by",
        "`scripts/seed_bytes.py` from pinned checkouts: regenerate it, do not edit it. -/",
        "",
        "-- Array literals this long nest past the default recursion limit.",
        "set_option maxRecDepth 1000000",
        "",
        "namespace Seed",
        "",
    ]
    for name, root, path, what in FILES:
        data = pathlib.Path(roots[root], path).read_bytes()
        out.append(f"/-- {what}: `{path}` in {CHECKOUTS[root]}, {len(data)} bytes. -/")
        out.append(f"def {name} : Array UInt8 := {array(data)}")
        out.append("")
    out.append("end Seed")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
